#!/usr/bin/env node
// ───────────────────────────────────────────────────────────────
// Kone Cloud · approval-gate deployment evidence harness
//
// Produces live evidence that the DEPLOYED worker (not just the
// in-process test suite) rejects unapproved sends. Release blocker ③
// "审批门禁部署开启留证" requires this proof.
//
// Gate semantics are owned by CLOUD-COLLABORATION-DELIVERY.md §8.
// Request/response shapes are derived only from:
//   · kone-cloud/src/worker.ts   (route table + gate ordering)
//   · kone-cloud/src/utils.ts    (HTTP status map)
//   · kone-cloud/tests/*.test.ts (payload shapes)
//
// The harness creates its own fixture lead. It does NOT require a
// pre-existing lead for the gate-on proof:
//   A2  lead → approved at draftVersion N → queue at N+1
//       expect 409 DRAFT_VERSION_MISMATCH
//   A3  suppress the fixture email → queue at N
//       expect 403 SUPPRESSED
//
// A4 (APPROVAL_REQUIRED) is only meaningful for legacy leads that are
// already approved/queued with no approval anchor. The public API has
// no route that creates that state, so A4 is not_applicable unless a
// legacy lead id is supplied explicitly.
//
// Zero dependencies. Node 18+ (global fetch, crypto.randomUUID).
//
// Exit codes:
//   0  PASS
//   1  FAIL or INCOMPLETE
//   2  configuration error (missing/invalid env, bad CLI usage, no --allow-write)
//   3  network / transport error
// ───────────────────────────────────────────────────────────────
