function createAssertions() {
  const definitions = [
    ['A1', 'Reachability and version identifier'],
    ['A2', 'Deployed gate rejects a stale draft version (discriminator)'],
    ['A3', 'Deployed gate rejects a globally suppressed recipient'],
    ['A4', 'Deployed gate rejects a lead without an approval anchor (legacy leads only)'],
    ['A5', 'Rejected attempts leave lead status fail-closed'],
    ['A6', 'Rejected attempts create no outreach row (no double-send)'],
  ]
  return definitions.map(([id, name]) => ({
    id,
    name,
    expected: {},
    actual: {},
    verdict: null,
    reason: '',
    evidence: { gateOffWouldReturn: 'not executed' },
    requests: [],
  }))
}

function assertPass(assertion, actual, reason, evidence) {
  assertion.actual = actual
  assertion.verdict = 'pass'
  assertion.reason = reason || ''
  if (evidence) assertion.evidence = evidence
}

function assertFail(assertion, actual, reason, evidence) {
  assertion.actual = actual
  assertion.verdict = 'fail'
  assertion.reason = reason
  if (evidence) assertion.evidence = evidence
}

function assertSkip(assertion, actual, reason, evidence) {
  assertion.actual = actual
  assertion.verdict = 'skipped'
  assertion.reason = reason
  if (evidence) assertion.evidence = evidence
}

function assertNotApplicable(assertion, actual, reason, evidence) {
  assertion.actual = actual
  assertion.verdict = 'not_applicable'
  assertion.reason = reason
  if (evidence) assertion.evidence = evidence
}

