function parseArgs(argv) {
  const opts = { dryRun: false, help: false, out: null, allowWrite: false, legacyLeadId: null }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--dry-run') opts.dryRun = true
    else if (arg === '--allow-write') opts.allowWrite = true
    else if (arg === '--help' || arg === '-h') opts.help = true
    else if (arg === '--out') {
      const value = argv[i + 1]
      if (!value || value.startsWith('--')) throw new Error('--out requires a path')
      opts.out = value
      i += 1
    } else if (arg.startsWith('--out=')) {
      const value = arg.slice('--out='.length)
      if (!value) throw new Error('--out requires a path')
      opts.out = value
    } else if (arg === '--legacy-lead-id') {
      const value = argv[i + 1]
      if (!value || value.startsWith('--')) throw new Error('--legacy-lead-id requires a value')
      opts.legacyLeadId = value.trim()
      i += 1
    } else if (arg.startsWith('--legacy-lead-id=')) {
      const value = arg.slice('--legacy-lead-id='.length).trim()
      if (!value) throw new Error('--legacy-lead-id requires a value')
      opts.legacyLeadId = value
    } else {
      throw new Error(`Unknown argument: ${arg}`)
    }
  }
  return opts
}

function resolveLegacyLeadId(env, opts) {
  if (opts.legacyLeadId) return { id: opts.legacyLeadId, source: '--legacy-lead-id' }
  for (const key of LEGACY_ENV_KEYS) {
    const value = String(env[key] ?? '').trim()
    if (value) return { id: value, source: key }
  }
  return { id: '', source: null }
}

function loadConfig(env, opts) {
  const missing = REQUIRED_ENV.filter((key) => !String(env[key] ?? '').trim())
  const rawGate = String(env.KONE_CLOUD_EXPECT_GATE ?? 'on').trim().toLowerCase()
  const gate = rawGate === 'off' ? 'off' : 'on'
  const gateError = rawGate === 'on' || rawGate === 'off'
    ? null
    : `KONE_CLOUD_EXPECT_GATE must be "on" or "off" (got "${rawGate}")`
  const legacy = resolveLegacyLeadId(env, opts)

  let baseUrl = null
  let baseError = null
  const rawBase = String(env.KONE_CLOUD_BASE_URL ?? '').trim()
  if (rawBase) {
    try {
      const parsed = new URL(rawBase)
      if (!/^https?:$/.test(parsed.protocol) || !parsed.host) {
        throw new Error('must be an absolute http(s) URL')
      }
      baseUrl = parsed
    } catch (error) {
      baseError = `KONE_CLOUD_BASE_URL is invalid: ${error.message}`
    }
  }

  return {
    missing,
    baseUrl,
    baseError,
    gate,
    gateError,
    token: String(env.KONE_CLOUD_TOKEN ?? '').trim(),
    workspaceId: String(env.KONE_CLOUD_WORKSPACE_ID ?? '').trim(),
    legacyLeadId: legacy.id,
    legacyLeadSource: legacy.source,
  }
}

function joinUrl(baseUrl, suffix) {
  const basePath = baseUrl.pathname.replace(/\/+$/, '')
  return `${baseUrl.origin}${basePath}${suffix}`
}

function displayBase(cfg) {
  if (!cfg.baseUrl) return '[missing]'
  return `${cfg.baseUrl.origin}${cfg.baseUrl.pathname.replace(/\/+$/, '')}`
}

function maskEmail(email) {
  const at = email.lastIndexOf('@')
  if (at <= 0) return '***'
  return `${email[0]}***${email.slice(at)}`
}

function redact(text, token) {
  let out = String(text ?? '')
  if (token) out = out.split(token).join('[REDACTED_TOKEN]')
  out = out.replace(/Bearer\s+[A-Za-z0-9._~+/-]+=*/gi, 'Bearer [REDACTED_TOKEN]')
  out = out.replace(EMAIL_RE, (match) => maskEmail(match))
  return out.slice(0, BODY_LIMIT)
}

class TransportError extends Error {}

function recordResponse(ctx, request, response, text) {
  let parsed = null
  try {
    parsed = JSON.parse(text)
  } catch {
    parsed = null
  }
  const errorCode = parsed && parsed.success === false && typeof parsed.code === 'string'
    ? parsed.code
    : null
  const requestId = (parsed && typeof parsed.requestId === 'string' && parsed.requestId)
    || response.headers.get('x-request-id')
    || null
  const record = {
    method: request.method,
    path: request.path,
    requestId,
    httpStatus: response.status,
    errorCode,
    responseBody: redact(text, ctx.cfg.token),
    timestamp: request.startedAt,
  }
  const assertion = ctx.byId[ctx.current]
  if (assertion) assertion.requests.push(record)
  return { record, parsed, status: response.status }
}

async function httpCall(ctx, options) {
  const { method, path: routePath, body, auth = true, headers: extraHeaders = {} } = options
  const url = joinUrl(ctx.cfg.baseUrl, routePath)
  const headers = { Accept: 'application/json', Connection: 'close', ...extraHeaders }
  if (auth && ctx.cfg.token) headers.Authorization = `Bearer ${ctx.cfg.token}`
  if (body !== undefined) headers['Content-Type'] = 'application/json'

  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS)
  const startedAt = new Date().toISOString()
  let response
  try {
    response = await fetch(url, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: controller.signal,
    })
  } catch (error) {
    const cause = error && error.name === 'AbortError'
      ? `request timed out after ${REQUEST_TIMEOUT_MS}ms`
      : (error && error.message) || String(error)
    throw new TransportError(`${method} ${routePath} failed: ${cause}`)
  } finally {
    clearTimeout(timer)
  }

  const text = await response.text().catch(() => '')
  return recordResponse(ctx, { method, path: routePath, startedAt }, response, text)
}

async function readLead(ctx, leadId) {
  let offset = 0
  let lastStatus = null
  let lastCode = null
  for (let page = 0; page < MAX_LEAD_PAGES; page += 1) {
    const routePath = `/leads?limit=200&offset=${offset}`
    const result = await httpCall(ctx, { method: 'GET', path: routePath })
    lastStatus = result.status
    lastCode = result.record.errorCode
    if (result.status !== 200) {
      return { lead: null, readStatus: lastStatus, errorCode: lastCode, notFound: false }
    }
    const leads = result.parsed && result.parsed.data && Array.isArray(result.parsed.data.leads)
      ? result.parsed.data.leads
      : []
    const lead = leads.find((row) => row && row.id === leadId) || null
    if (lead) return { lead, readStatus: 200, errorCode: null, notFound: false }
    if (leads.length < 200) {
      return { lead: null, readStatus: 200, errorCode: null, notFound: true }
    }
    offset += 200
  }
  return { lead: null, readStatus: lastStatus, errorCode: lastCode, notFound: true, truncated: true }
}

async function listOutreach(ctx, leadId) {
  const routePath = `/outreach/status?leadId=${encodeURIComponent(leadId)}&limit=200`
  const result = await httpCall(ctx, { method: 'GET', path: routePath })
  if (result.status !== 200) {
    return { rows: null, readStatus: result.status, errorCode: result.record.errorCode }
  }
  const rows = result.parsed && result.parsed.data && Array.isArray(result.parsed.data.outreach)
    ? result.parsed.data.outreach
    : []
  return { rows, readStatus: 200, errorCode: null }
}

