async function runLive(cfg, outPath) {
  const generatedAt = new Date().toISOString()
  const assertions = createAssertions()
  const byId = Object.fromEntries(assertions.map((assertion) => [assertion.id, assertion]))
  const notes = []
  const fixture = makeFixture()
  const ctx = {
    cfg,
    assertions,
    byId,
    current: 'A1',
    workerVersionIdentifier: 'not-exposed',
    fixture,
  }

  console.log('Kone Cloud approval-gate deployment evidence harness')
  console.log(`base: ${displayBase(cfg)}`)
  console.log(`expected gate: ${cfg.gate}`)
  console.log(`fixture lead: generated (${fixture.localRefId})`)
  console.log(`legacy lead for A4: ${cfg.legacyLeadId ? `[set via ${cfg.legacyLeadSource}]` : '[not set] -> not_applicable'}`)
  console.log('')

  try {
    // ── A1 · reachability ──
    ctx.current = 'A1'
    const health = await httpCall(ctx, { method: ROUTE.health.method, path: ROUTE.health.path, auth: false })
    const healthData = dataOf(health)
    const schemaVersion = typeof healthData.schemaVersion === 'string' && healthData.schemaVersion
      ? healthData.schemaVersion
      : null
    ctx.workerVersionIdentifier = schemaVersion || 'not-exposed'
    const a1 = byId.A1
    a1.expected = { httpStatus: 200, status: 'ok' }
    if (health.status === 200 && healthData.status === 'ok') {
      assertPass(a1, { httpStatus: health.status, status: healthData.status, schemaVersion }, schemaVersion
        ? `worker /healthz reports ok; schemaVersion=${schemaVersion}`
        : 'worker /healthz reports ok; no version identifier exposed', {
        gateOffWouldReturn: 'n/a (read-only)',
        source: ROUTE.health.source,
      })
    } else {
      assertFail(a1, { httpStatus: health.status, status: healthData.status ?? null, schemaVersion }, `health endpoint returned HTTP ${health.status}`, {
        gateOffWouldReturn: 'n/a (read-only)',
        source: ROUTE.health.source,
      })
    }
    if (schemaVersion) {
      notes.push('workerVersionIdentifier is the /healthz schemaVersion; worker.ts exposes no build/commit identifier.')
    } else {
      notes.push('worker.ts /healthz exposes no version identifier; recorded "not-exposed".')
    }

    // ── A2 · create fixture → approve N → queue N+1 ──
    ctx.current = 'A2'
    const a2 = byId.A2
    const gateOn = cfg.gate === 'on'
    let fixtureCreated = false
    let fixtureApproved = false

    a2.expected = {
      createLead: { httpStatus: 200, status: 'scored' },
      approval: { httpStatus: 200, status: 'approved', draftVersion: FIXTURE_DRAFT_VERSION },
      queue: gateOn
        ? { httpStatus: 409, errorCode: 'DRAFT_VERSION_MISMATCH' }
        : { httpStatus: 200 },
    }
    a2.evidence = {
      gateOffWouldReturn: '200 queued (gate ⑦ is skipped when APPROVAL_GATE_ENABLED is not "true")',
      source: GATE_SOURCE.draftMismatch,
    }

    const create = await createFixtureLead(ctx, fixture)
    const createData = dataOf(create)
    const createCode = codeOf(create)
    const createdLeadId = typeof createData.id === 'string' ? createData.id : null
    fixture.leadId = createdLeadId

    if (create.status !== 200 || createCode || !createdLeadId || createData.status !== 'scored') {
      const reason = create.status === 200 && !createCode && createdLeadId && createData.status !== 'scored'
        ? `POST /leads returned status "${createData.status ?? 'missing'}" instead of "scored"; cannot build the A2 discriminator.`
        : `fixture creation failed: HTTP ${create.status}${createCode ? ` ${createCode}` : ''}${createdLeadId ? '' : ' (no lead id returned)'}`
      assertFail(a2, {
        createHttpStatus: create.status,
        createErrorCode: createCode,
        createLeadStatus: createData.status ?? null,
        leadIdReturned: Boolean(createdLeadId),
        approvalHttpStatus: null,
        queueHttpStatus: null,
        queueErrorCode: null,
      }, reason)
      notes.push('A2 fixture creation failed; A2/A5/A6 cannot prove the deployed gate for this run.')
    } else {
      fixtureCreated = true
      const approval = await approveFixtureLead(ctx, createdLeadId)
      const approvalData = dataOf(approval)
      const approvalCode = codeOf(approval)
      const approved = approval.status === 200 && approvalCode === null && approvalData.status === 'approved'
      fixtureApproved = approved

      let queue = null
      if (approved) {
        queue = await queueFixtureLead(ctx, createdLeadId, FIXTURE_SUBMITTED_VERSION, 0)
      }

      const queueCode = queue ? codeOf(queue) : null
      const queueData = queue ? dataOf(queue) : {}
      a2.actual = {
        leadId: createdLeadId,
        emailMasked: maskEmail(fixture.email),
        createHttpStatus: create.status,
        createLeadStatus: createData.status,
        approvalHttpStatus: approval.status,
        approvalErrorCode: approvalCode,
        approvalStatus: approvalData.status ?? null,
        approvedDraftVersion: FIXTURE_DRAFT_VERSION,
        submittedDraftVersion: FIXTURE_SUBMITTED_VERSION,
        queueHttpStatus: queue ? queue.status : null,
        queueErrorCode: queueCode,
        queued: queueData.queued === true,
        idempotent: queueData.idempotent === true,
        outreachId: typeof queueData.id === 'string' ? queueData.id : null,
      }

      if (!approved) {
        assertFail(a2, a2.actual, `could not create the approval anchor: HTTP ${approval.status}${approvalCode ? ` ${approvalCode}` : ''}; lead status "${approvalData.status ?? 'unknown'}"`, a2.evidence)
      } else if (gateOn) {
        if (queue.status === 409 && queueCode === 'DRAFT_VERSION_MISMATCH') {
          assertPass(a2, a2.actual, 'approval at draftVersion N did not authorize a send at N+1', a2.evidence)
        } else if (queue.status === 200) {
          const reason = queueData.idempotent === true
            ? 'HARD FAILURE: HTTP 200 came from the pre-gate idempotency short-circuit, not from the approval gate; the mismatch discriminator was not exercised.'
            : 'HARD FAILURE: deployed gate accepted a send at draftVersion N+1 with only an N approval. The draft-version gate is NOT enforcing.'
          assertFail(a2, a2.actual, reason, a2.evidence)
          notes.push('A2 HARD FAILURE: the deployed worker accepted a stale draftVersion.')
        } else if (queueCode === 'LEAD_NOT_APPROVED') {
          assertFail(a2, a2.actual, 'lead was rejected before gate ⑦ with LEAD_NOT_APPROVED; the approval write did not take effect.', a2.evidence)
        } else if (queueCode === 'APPROVAL_REQUIRED') {
          assertFail(a2, a2.actual, 'gate ⑦ returned APPROVAL_REQUIRED even though POST /approvals returned 200; approval lookup is inconsistent.', a2.evidence)
        } else if (queueCode === 'SUPPRESSED') {
          assertFail(a2, a2.actual, 'gate ⑥ returned SUPPRESSED before the draft-version check; the generated fixture email was unexpectedly already suppressed.', a2.evidence)
        } else {
          assertFail(a2, a2.actual, `expected 409 DRAFT_VERSION_MISMATCH, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a2.evidence)
        }
      } else if (queue.status === 200) {
        assertPass(a2, a2.actual, 'gate is disabled as expected (backward-compat deployment)', a2.evidence)
        notes.push('Gate-off mode queued a probe outreach row; a later cron run may attempt delivery. Use a disposable workspace.')
      } else {
        assertFail(a2, a2.actual, `expected HTTP 200 with the gate off, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a2.evidence)
      }
    }

    // ── A3 · suppress the fixture email → queue at matching N ──
    ctx.current = 'A3'
    const a3 = byId.A3
    a3.expected = {
      unsubscribe: { httpStatus: 200, suppressedOrAlready: true },
      queue: gateOn
        ? { httpStatus: 403, errorCode: 'SUPPRESSED' }
        : { httpStatus: 200 },
    }
    a3.evidence = {
      gateOffWouldReturn: '200 (accepted, or idempotent replay of the A2 row after unsubscribe marks it failed)',
      source: GATE_SOURCE.suppression,
    }
    if (!fixtureApproved) {
      assertSkip(a3, { executed: false }, 'fixture was not created and approved; the suppression probe cannot target gate ⑥.', a3.evidence)
    } else {
      const unsubscribe = await httpCall(ctx, {
        method: ROUTE.unsubscribe.method,
        path: ROUTE.unsubscribe.path,
        body: { email: fixture.email, source: 'approval-gate-evidence' },
      })
      const unsubscribeData = dataOf(unsubscribe)
      const unsubscribeCode = codeOf(unsubscribe)
      const unsubscribeOk = unsubscribe.status === 200 && unsubscribeCode === null
        && (unsubscribeData.suppressed === true || unsubscribeData.alreadySuppressed === true)

      let queue = null
      if (unsubscribeOk) {
        queue = await queueFixtureLead(ctx, fixture.leadId, FIXTURE_DRAFT_VERSION, 0)
      }
      const queueCode = queue ? codeOf(queue) : null
      const queueData = queue ? dataOf(queue) : {}
      a3.actual = {
        leadId: fixture.leadId,
        emailMasked: maskEmail(fixture.email),
        unsubscribeHttpStatus: unsubscribe.status,
        unsubscribeErrorCode: unsubscribeCode,
        suppressed: unsubscribeData.suppressed === true,
        alreadySuppressed: unsubscribeData.alreadySuppressed === true,
        submittedDraftVersion: FIXTURE_DRAFT_VERSION,
        queueHttpStatus: queue ? queue.status : null,
        queueErrorCode: queueCode,
        queued: queueData.queued === true,
        idempotent: queueData.idempotent === true,
        outreachId: typeof queueData.id === 'string' ? queueData.id : null,
      }

      if (!unsubscribeOk) {
        assertFail(a3, a3.actual, `POST /suppressions/unsubscribe did not confirm suppression: HTTP ${unsubscribe.status}${unsubscribeCode ? ` ${unsubscribeCode}` : ''}`, a3.evidence)
      } else if (gateOn) {
        if (queue.status === 403 && queueCode === 'SUPPRESSED') {
          assertPass(a3, a3.actual, 'deployed worker rejected the suppressed recipient with SUPPRESSED', a3.evidence)
        } else if (queue.status === 200) {
          assertFail(a3, a3.actual, 'HARD FAILURE: a globally suppressed recipient was accepted (HTTP 200). Gate ⑥ is NOT enforcing.', a3.evidence)
          notes.push('A3 HARD FAILURE: the deployed worker accepted a globally suppressed recipient.')
        } else if (queueCode === 'LEAD_NOT_APPROVED') {
          assertFail(a3, a3.actual, 'lead was rejected before gate ⑥ with LEAD_NOT_APPROVED; the approval anchor is missing.', a3.evidence)
        } else if (queueCode === 'APPROVAL_REQUIRED') {
          assertFail(a3, a3.actual, 'gate ⑦ returned APPROVAL_REQUIRED before gate ⑥ was reached; suppression was not exercised.', a3.evidence)
        } else if (queueCode === 'DRAFT_VERSION_MISMATCH') {
          assertFail(a3, a3.actual, 'gate ⑦ returned DRAFT_VERSION_MISMATCH before gate ⑥ was reached; suppression was not exercised.', a3.evidence)
        } else {
          assertFail(a3, a3.actual, `expected 403 SUPPRESSED, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a3.evidence)
        }
      } else if (queue.status === 200) {
        assertPass(a3, a3.actual, 'gate is disabled as expected: suppressed recipient was not blocked at queue time', a3.evidence)
      } else {
        assertFail(a3, a3.actual, `expected HTTP 200 with the gate off, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a3.evidence)
      }
      notes.push('A3 added a GLOBAL, irreversible suppression entry for the generated fixture email.')
    }

    // ── A4 · legacy lead without an approval anchor ──
    ctx.current = 'A4'
    const a4 = byId.A4
    a4.evidence = {
      gateOffWouldReturn: '200 (gate ⑦ skipped when APPROVAL_GATE_ENABLED is not "true")',
      source: GATE_SOURCE.noApproval,
    }
    if (!cfg.legacyLeadId) {
      a4.expected = { executed: false, reason: 'no legacy lead supplied' }
      assertNotApplicable(a4, { executed: false, legacyLeadId: null }, 'APPROVAL_REQUIRED requires a lead in status approved/queued with a NULL approval anchor; the only public API path to approved sets the anchor, so this state is legacy/DB-only. Covered in-process by kone-cloud/tests/approval-gate.test.ts:155-161.', a4.evidence)
    } else {
      a4.expected = gateOn
        ? { httpStatus: 403, errorCode: 'APPROVAL_REQUIRED' }
        : { httpStatus: 200 }
      const queue = await httpCall(ctx, {
        method: ROUTE.queue.method,
        path: ROUTE.queue.path,
        body: { leadId: cfg.legacyLeadId, subject: PROBE_SUBJECT, body: PROBE_BODY },
      })
      const queueCode = codeOf(queue)
      const queueData = dataOf(queue)
      a4.actual = {
        leadId: cfg.legacyLeadId,
        source: cfg.legacyLeadSource,
        queueHttpStatus: queue.status,
        queueErrorCode: queueCode,
        queued: queueData.queued === true,
        idempotent: queueData.idempotent === true,
        outreachId: typeof queueData.id === 'string' ? queueData.id : null,
      }
      if (gateOn) {
        if (queue.status === 403 && queueCode === 'APPROVAL_REQUIRED') {
          assertPass(a4, a4.actual, 'deployed worker rejected a lead with no approval anchor', a4.evidence)
        } else if (queue.status === 200) {
          const reason = queueData.idempotent === true
            ? 'HTTP 200 came from the pre-gate idempotency short-circuit; the legacy lead already has a pending outreach row. Remove that row or use another legacy lead.'
            : 'HARD FAILURE: deployed gate accepted a legacy lead with no approval anchor (HTTP 200).'
          assertFail(a4, a4.actual, reason, a4.evidence)
        } else if (queueCode === 'LEAD_NOT_APPROVED') {
          assertFail(a4, a4.actual, 'legacy lead is not status approved/queued, so gate ⑦ was never reached (worker.ts:803-805).', a4.evidence)
        } else if (queueCode === 'SUPPRESSED') {
          assertFail(a4, a4.actual, 'gate ⑥ rejected before the approval check; use a non-suppressed legacy lead.', a4.evidence)
        } else if (queueCode === 'COMPANY_CONFLICT') {
          assertFail(a4, a4.actual, 'gate ⑤ rejected before the approval check; use a legacy lead without an active company protection period.', a4.evidence)
        } else if (queueCode === 'DRAFT_VERSION_MISMATCH') {
          assertFail(a4, a4.actual, 'legacy lead already has an approval record, so it is not an APPROVAL_REQUIRED candidate.', a4.evidence)
        } else {
          assertFail(a4, a4.actual, `expected 403 APPROVAL_REQUIRED, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a4.evidence)
        }
      } else if (queue.status === 200) {
        assertPass(a4, a4.actual, 'gate is disabled as expected: legacy lead was accepted without an approval anchor', a4.evidence)
      } else {
        assertFail(a4, a4.actual, `expected HTTP 200 with the gate off, got HTTP ${queue.status}${queueCode ? ` ${queueCode}` : ''}`, a4.evidence)
      }
    }

    // ── A5 · final lead state ──
    ctx.current = 'A5'
    const a5 = byId.A5
    a5.evidence = {
      gateOffWouldReturn: gateOn ? 'n/a (gate expected on)' : 'queued (A2 accepted the send)',
      source: ROUTE.leads.source,
    }
    if (!fixtureApproved) {
      assertSkip(a5, { executed: false }, 'fixture lead was not created and approved; final status cannot prove fail-closed behavior.', a5.evidence)
    } else {
      const read = await readLead(ctx, fixture.leadId)
      const finalStatus = leadStatusOf(read)
      const workspaceId = read.lead && typeof read.lead.workspace_id === 'string' ? read.lead.workspace_id : null
      const workspaceMatches = workspaceId !== null && workspaceId === cfg.workspaceId
      a5.actual = {
        leadId: fixture.leadId,
        readHttpStatus: read.readStatus,
        readErrorCode: read.errorCode,
        notFound: read.notFound === true,
        workspaceMatches,
        finalStatus,
      }
      if (read.readStatus !== 200) {
        assertFail(a5, a5.actual, `GET /leads returned HTTP ${read.readStatus}${read.errorCode ? ` ${read.errorCode}` : ''}; cannot verify final lead state.`, a5.evidence)
      } else if (read.notFound) {
        assertFail(a5, a5.actual, 'fixture lead was not found in GET /leads; cannot verify final lead state.', a5.evidence)
      } else if (!workspaceMatches) {
        assertFail(a5, a5.actual, 'KONE_CLOUD_WORKSPACE_ID does not match the fixture lead workspace_id returned by GET /leads.', a5.evidence)
      } else if (gateOn) {
        a5.expected = {
          finalStatus: 'approved',
          notQueued: true,
          notSentOrDelivered: true,
        }
        const notQueued = finalStatus !== 'queued'
        const notSent = finalStatus !== 'sent' && finalStatus !== 'delivered'
        if (finalStatus === 'approved' && notQueued && notSent) {
          assertPass(a5, a5.actual, 'lead stayed at "approved" after both rejected attempts; no queued/sent/delivered transition.', a5.evidence)
        } else {
          assertFail(a5, a5.actual, `expected final status "approved" with no queued/sent/delivered transition, got "${finalStatus}".`, a5.evidence)
        }
      } else {
        a5.expected = {
          finalStatusAllowed: ['approved', 'queued'],
          notSentOrDelivered: true,
        }
        const allowed = finalStatus === 'approved' || finalStatus === 'queued'
        const notSent = finalStatus !== 'sent' && finalStatus !== 'delivered'
        if (allowed && notSent) {
          assertPass(a5, a5.actual, `gate-off run left lead at "${finalStatus}"; no sent/delivered state.`, a5.evidence)
        } else {
          assertFail(a5, a5.actual, `gate-off lead state "${finalStatus}" is outside {approved, queued} or indicates sent/delivered.`, a5.evidence)
        }
      }
    }

    // ── A6 · outreach rows ──
    ctx.current = 'A6'
    const a6 = byId.A6
    a6.evidence = {
      gateOffWouldReturn: gateOn ? 'n/a (gate expected on)' : '1 pending row from A2; A3 replays it after unsubscribe marks it failed',
      source: ROUTE.outreachStatus.source,
    }
    if (!fixtureApproved) {
      assertSkip(a6, { executed: false }, 'fixture lead was not created and approved; outreach row count cannot prove fail-closed behavior.', a6.evidence)
    } else {
      const outreach = await listOutreach(ctx, fixture.leadId)
      if (outreach.readStatus !== 200 || !outreach.rows) {
        a6.expected = { outreachReadable: true }
        assertFail(a6, {
          httpStatus: outreach.readStatus,
          errorCode: outreach.errorCode,
        }, 'GET /outreach/status did not return 200; cannot verify row counts.', a6.evidence)
      } else {
        const rows = outreach.rows
        const pendingCount = rows.filter((row) => row && row.status === 'pending').length
        const sentOrDelivered = rows.filter((row) => row && (row.status === 'sent' || row.status === 'delivered')).length
        const statuses = rows.map((row) => row && row.status).filter(Boolean).sort()
        a6.actual = {
          rowCount: rows.length,
          pendingCount,
          sentOrDelivered,
          statuses,
        }
        if (gateOn) {
          a6.expected = { rowCount: 0, sentOrDelivered: 0 }
          if (rows.length === 0) {
            assertPass(a6, a6.actual, 'both rejected attempts created no outreach row (no double-send).', a6.evidence)
          } else {
            assertFail(a6, a6.actual, `${rows.length} outreach row(s) exist for the fixture lead; a rejected attempt was not fail-closed.`, a6.evidence)
            notes.push('A6 HARD FAILURE: a rejected attempt left an outreach row behind.')
          }
        } else {
          a6.expected = { rowCountAtMost: 2, pendingCountAtMost: 1, sentOrDelivered: 0 }
          if (rows.length <= 2 && pendingCount <= 1 && sentOrDelivered === 0) {
            assertPass(a6, a6.actual, 'gate-off run left at most one pending outreach row and nothing sent/delivered.', a6.evidence)
          } else {
            assertFail(a6, a6.actual, `gate-off row budget failed: rows=${rows.length}, pending=${pendingCount}, sentOrDelivered=${sentOrDelivered}.`, a6.evidence)
          }
        }
      }
    }

    notes.push('The fixture lead, its approval/company/contact rows, and the global suppression entry are not deleted: the deployed API has no DELETE route. Use a staging workspace.')
    notes.push('KONE_CLOUD_WORKSPACE_ID is cross-checked against lead.workspace_id from GET /leads; the worker also scopes requests by the bearer token (auth.ts:22-38).')
    notes.push('Evidence redacts the bearer token, masks email local parts, and never records request headers or the Idempotency-Key.')

    return finishLive(ctx, generatedAt, outPath, notes, null)
  } catch (error) {
    const isTransport = error instanceof TransportError
    const current = ctx.byId[ctx.current]
    if (current) {
      current.verdict = 'fail'
      current.actual = { ...(current.actual || {}), error: error.message }
      current.reason = `${isTransport ? 'transport/network error' : 'unexpected harness error'}: ${error.message}`
    }
    for (const assertion of assertions) {
      if (assertion.verdict === null) {
        assertSkip(assertion, { executed: false }, `not executed: ${isTransport ? 'transport error' : 'harness error'} during ${ctx.current}`)
      }
    }
    notes.push(isTransport
      ? `Transport error during ${ctx.current}; evidence written fail-closed.`
      : `Unexpected harness error during ${ctx.current}; evidence written fail-closed.`)
    return finishLive(ctx, generatedAt, outPath, notes, isTransport ? error : null)
  }
}

function computeVerdict(ctx, transportError) {
  if (transportError) return 'FAIL'
  if (ctx.assertions.some((assertion) => assertion.verdict === 'fail')) return 'FAIL'
  if (ctx.assertions.some((assertion) => assertion.verdict === 'skipped')) return 'INCOMPLETE'
  const a2 = ctx.byId.A2
  const a3 = ctx.byId.A3
  if (!a2 || !a3 || a2.verdict !== 'pass' || a3.verdict !== 'pass') return 'INCOMPLETE'
  return 'PASS'
}

function finishLive(ctx, generatedAt, outPath, notes, transportError) {
  const verdict = computeVerdict(ctx, transportError)

  const evidence = {
    schemaVersion: 2,
    kind: 'approval-gate-deployment-evidence',
    generatedAt,
    baseUrl: displayBase(ctx.cfg),
    expectedGateState: ctx.cfg.gate,
    workerVersionIdentifier: ctx.workerVersionIdentifier,
    allowWrite: true,
    legacyLead: ctx.cfg.legacyLeadId
      ? { id: ctx.cfg.legacyLeadId, source: ctx.cfg.legacyLeadSource }
      : null,
    fixtures: {
      leadId: ctx.fixture.leadId,
      emailMasked: maskEmail(ctx.fixture.email),
      domain: ctx.fixture.domain,
      localRefId: ctx.fixture.localRefId,
    },
    cleanup: {
      supported: false,
      note: 'No DELETE route; fixture rows remain in the workspace — use a staging workspace.',
    },
    assertions: ctx.assertions.map((assertion) => ({
      id: assertion.id,
      name: assertion.name,
      expected: assertion.expected,
      actual: assertion.actual,
      verdict: assertion.verdict,
      reason: assertion.reason,
      evidence: assertion.evidence,
      requests: assertion.requests,
    })),
    verdict,
    notes,
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, `${JSON.stringify(evidence, null, 2)}\n`, 'utf8')

  console.log('Assertions:')
  for (const assertion of ctx.assertions) {
    const label = String(assertion.verdict || 'skipped').toUpperCase().padEnd(14)
    console.log(`  [${label}] ${assertion.id} ${assertion.name}`)
    if (assertion.reason) console.log(`                 ${assertion.reason}`)
    for (const request of assertion.requests) {
      const code = request.errorCode ? ` ${request.errorCode}` : ''
      const reqId = request.requestId ? ` req=${request.requestId}` : ''
      console.log(`                 ${request.method} ${request.path} -> ${request.httpStatus}${code}${reqId}`)
    }
  }
  console.log('')

  if (ctx.cfg.gate === 'on') {
    const a2 = ctx.byId.A2
    if (a2 && a2.actual && a2.actual.queueHttpStatus === 200) {
      console.error('HARD FAILURE: A2 accepted a stale draftVersion. The deployed draft-version gate is NOT enforcing.')
    }
    const a3 = ctx.byId.A3
    if (a3 && a3.actual && a3.actual.queueHttpStatus === 200) {
      console.error('HARD FAILURE: A3 accepted a globally suppressed recipient. The deployed suppression gate is NOT enforcing.')
    }
  }

  console.log(`verdict: ${verdict}`)
  console.log(`evidence: ${outPath}`)

  if (transportError) return EXIT.TRANSPORT
  return verdict === 'PASS' ? EXIT.PASS : EXIT.FAIL
}

function defaultOutPath() {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-')
  return path.join(ROOT_DIR, 'tests', `approval-gate-evidence-${stamp}.json`)
}

async function main() {
  let opts
  try {
    opts = parseArgs(process.argv.slice(2))
  } catch (error) {
    console.error(`configuration error: ${error.message}`)
    console.error('')
    console.error(usage())
    return EXIT.CONFIG
  }

  if (opts.help) {
    console.log(usage())
    return EXIT.PASS
  }

  const cfg = loadConfig(process.env, opts)

  if (opts.dryRun) {
    printDryRun(cfg)
    return EXIT.PASS
  }

  const configErrors = []
  if (cfg.missing.length > 0) configErrors.push(`missing required environment variables: ${cfg.missing.join(', ')}`)
  if (cfg.baseError) configErrors.push(cfg.baseError)
  if (cfg.gateError) configErrors.push(cfg.gateError)
  if (!opts.allowWrite) configErrors.push('live mode requires --allow-write')

  if (configErrors.length > 0) {
    console.error('configuration error: live mode cannot start.')
    console.error('')
    if (cfg.missing.length > 0) {
      console.error('Missing required environment variables:')
      for (const key of cfg.missing) console.error(`  - ${key}`)
    }
    if (cfg.baseError) console.error(`Invalid URL: ${cfg.baseError}`)
    if (cfg.gateError) console.error(`Invalid gate state: ${cfg.gateError}`)
    if (!opts.allowWrite) {
      console.error('Live mode writes (re-run with --allow-write to acknowledge):')
      for (const write of WRITE_OPERATIONS) console.error(`  - ${write}`)
    }
    console.error('')
    console.error('No request was sent. Fix the configuration above and re-run.')
    return EXIT.CONFIG
  }

  const outPath = opts.out ? path.resolve(process.cwd(), opts.out) : defaultOutPath()
  return runLive(cfg, outPath)
}

main()
  .then((code) => {
    process.exitCode = code
  })
  .catch((error) => {
    console.error('unexpected error:', error && error.message ? error.message : String(error))
    process.exitCode = EXIT.CONFIG
  })
